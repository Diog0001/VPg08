"""Шаблоны промптов для пайплайна суммаризации и ответов по контексту."""

from haystack.dataclasses import ChatMessage

SYSTEM_PROMPT = """Ты помощник рабочей команды в общем Telegram-чате.
Опирайся только на найденный контекст и текущий диалог. Не выдумывай факты.
Если упоминаешь реплику, указывай автора и суть: кто, когда и что сказал.
Если контекста мало — прямо скажи об этом.
Если это спор — кратко изложи тезисы сторон и дай своё мнение.
Если это выбор действий — подведи итог и дай рекомендацию.
Отвечай на языке чата, обычно по-русски. Пиши коротко и по делу."""

CONTEXT_BLOCK = """
Текущий запрос:
{{ query }}

Диалог сессии / последние реплики:
{{ dialogue }}

Найденные сообщения из памяти чата:
{% if documents %}
{% for doc in documents %}
- {{ doc.meta.username | default("участник") }} ({{ doc.meta.date | default("без даты") }}): {{ doc.content }}
{% endfor %}
{% else %}
(ничего не найдено)
{% endif %}
"""

ANSWER_TEMPLATE = [
    ChatMessage.from_system(SYSTEM_PROMPT),
    ChatMessage.from_user(
        "Ответь на запрос по контексту обсуждения. "
        "Если люди спрашивают «что думаешь?» — выскажи мнение по теме чата, "
        "опираясь на конкретные реплики.\n"
        + CONTEXT_BLOCK
    ),
]

SUMMARIZE_TEMPLATE = [
    ChatMessage.from_system(SYSTEM_PROMPT),
    ChatMessage.from_user(
        "Подведи итог обсуждения.\n"
        "Если это спор — тезисы сторон и твоё мнение.\n"
        "Если это решение или выбор действий — итог и рекомендация.\n"
        "Иначе — тема, ключевые тезисы и как можно продолжить.\n"
        + CONTEXT_BLOCK
    ),
]
